// Shareable report card (optimization doc §2.D) -- the zero-cost growth flywheel.
//
// Rendered as PURE ASCII / Markdown (no box-drawing, emoji, or ANSI) and passed through `clean()`
// so it never mojibakes in a GBK Windows console -- the card is meant to be screenshotted and posted,
// and a mojibaked card would undermine the exact thing it is trying to grow. It summarises the scan
// into a few scannable lines an agent (or a human) can read in one glance.
import type { Check } from "../types";
import { clean } from "../glyphs";

type WinLevel = "ok" | "warn" | "block";

function windowsStatus(win: any): { label: string; level: WinLevel } {
  if (!win || !win.windows) return { label: "n/a (not Windows)", level: "ok" };
  if (win.languageMode && /constrained/i.test(String(win.languageMode)))
    return { label: "BLOCK (Constrained Language Mode)", level: "block" };
  const policyBlocked = Array.isArray(win.executionPolicy)
    ? win.executionPolicy.some((r: any) => /^(Restricted|AllSigned)$/i.test(r.level))
    : false;
  if (policyBlocked || win.schannelRevokeCheck === true || win.safeDeleteActive === true)
    return { label: "WARN (policy / revocation / safe-delete)", level: "warn" };
  return { label: "OK", level: "ok" };
}

/** Render the manifest as a shareable ASCII/Markdown card. */
export function renderCard(m: any): string {
  const meta = m.meta || {};
  const sys = m.system || {};
  const sum = m.summary || {};
  const env = m.environments || {};
  const win = m.windows || {};
  const sdks = m.sdks || {};
  const conflicts = m.conflicts || {};
  const ics = sum.issueCountBySeverity || {};
  const secrets = (m.checks || []).filter(
    (c: Check) => c.Kind === "secret" && (c.Severity === "warn" || c.Severity === "error" || c.Severity === "missing"),
  ).length;
  const ws = windowsStatus(win);

  const lines: string[] = [];
  lines.push(`# devmap ${meta.version || ""} - AI agent 的环境可靠性保险`);
  lines.push("");
  lines.push(`Host: ${sys.hostname || "?"}  ${sys.platform || "?"}/${sys.arch || "?"}  PATH dirs: ${sys.pathDirCount ?? "?"}`);
  lines.push("");
  lines.push(`- Tools: ${sum.totalInstallations ?? 0} across ${sum.runtimeKinds ?? 0} runtimes / ${sum.packageManagerKinds ?? 0} pkg-mgrs / ${sum.ideKinds ?? 0} IDEs`);
  lines.push(`- Conflicts: PATH ${conflicts.pathConflicts?.length ?? 0} · multi-version ${sum.toolsWithMultipleVersions ?? 0} · ghost ${conflicts.ghostBinaries?.length ?? 0}`);
  lines.push(`- Issues: ${ics.error ?? 0} error · ${ics.warn ?? 0} warn · ${ics.info ?? 0} info`);
  lines.push(`- Windows pre-flight: ${ws.label}`);
  const sdkBits: string[] = [];
  if (sdks.android)
    sdkBits.push(`Android ${sdks.android.sdkHome ? "home set" : "home MISSING"}${sdks.android.ndk?.length ? ` (NDK x${sdks.android.ndk.length})` : ""}`);
  if (sdks.flutter) sdkBits.push(`Flutter ${sdks.flutter.version || "?"}${sdks.flutter.channel ? "/" + sdks.flutter.channel : ""}`);
  if (sdks.dart) sdkBits.push(`Dart ${sdks.dart.version || "?"}`);
  lines.push(`- Mobile SDK: ${sdkBits.length ? sdkBits.join(" · ") : "none detected"}`);
  lines.push(`- Secrets: ${secrets} hit(s) (redacted)`);
  lines.push("");
  lines.push("Generated by `npx devmap` · github.com/StevenLOL/devmap");
  return clean(lines.join("\n"));
}
